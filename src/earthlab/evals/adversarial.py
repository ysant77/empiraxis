"""Run the adversarial scientific QA suite and report each case against its expected outcome.

A case names one existing deterministic check. The suite counts missed attacks and false
refusals of valid controls apart. It calls no model and no network.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import Field

from earthlab.contracts import Strict
from earthlab.evals.adversarial_checks import CHECKS, NEEDS_DATA, NEEDS_REPLAY

SUITE = Path("evals/adversarial_scientific_v1.yaml")
DATA_DIR = Path("data/nea")
REPLAY_DIR = Path("examples/replay")
LIMITS = (
    "- Each case tests one input against one check. A pass does not show resistance to other "
    "inputs.",
    "- `bearing_mean` and `rain_rate` compare a claimed number with production geometry. No "
    "production guard reads such a claim; the met code averages u and v and keeps totals apart.",
    "- `approval` uses a test key in a temporary store. Forged and mismatched cases write the "
    "approval file directly, as an attacker with file access would.",
    "- No case calls a model. The suite tests the deterministic gates, not model behaviour.",
)


class Case(Strict):
    id: str
    category: int = Field(ge=1, le=14)
    role: Literal["attack", "control"]
    expected: Literal["refuse", "allow"]
    check: str
    input: dict[str, Any]


class Gap(Strict):
    category: int
    gap: str


class Suite(Strict):
    version: int
    cases: tuple[Case, ...]
    untested: tuple[Gap, ...] = ()


class CaseResult(Strict):
    id: str
    category: int
    role: str
    check: str
    expected: str
    observed: Literal["refuse", "allow", "error"]
    evidence: str

    @property
    def correct(self) -> bool:
        return self.observed == self.expected


def load_suite(path: Path = SUITE) -> Suite:
    return Suite.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def run_case(case: Case, data_dir: Path = DATA_DIR, replay_dir: Path = REPLAY_DIR) -> CaseResult:
    args = dict(case.input)
    if case.check in NEEDS_DATA:
        args["data_dir"] = data_dir
    if case.check in NEEDS_REPLAY:
        args["replay_root"] = replay_dir
    try:
        refused, evidence = CHECKS[case.check](**args)
        observed: Literal["refuse", "allow", "error"] = "refuse" if refused else "allow"
    except Exception as exc:  # an adapter error is a result, not a crash
        observed, evidence = "error", f"{type(exc).__name__}: {exc}"
    return CaseResult(
        id=case.id, category=case.category, role=case.role, check=case.check,
        expected=case.expected, observed=observed, evidence=evidence[:300],
    )  # fmt: skip


def summary(results: list[CaseResult]) -> dict[str, Any]:
    attacks = [r for r in results if r.role == "attack"]
    controls = [r for r in results if r.role == "control"]
    return {
        "cases": len(results),
        "attacks_refused": sum(r.observed == "refuse" for r in attacks),
        "attacks": len(attacks),
        "controls_allowed": sum(r.observed == "allow" for r in controls),
        "controls": len(controls),
        "errors": sum(r.observed == "error" for r in results),
        "by_category": dict(sorted(Counter(r.category for r in results).items())),
    }


def render(suite: Suite, results: list[CaseResult]) -> str:
    """The Markdown report: totals, each case, and the gaps with no check."""
    total = summary(results)
    lines = [
        f"# Adversarial scientific QA, suite version {suite.version}",
        "",
        "Generated by `uv run python scripts/run_adversarial_suite.py`. No model and no network.",
        "",
        f"- Attacks refused: {total['attacks_refused']} of {total['attacks']}.",
        f"- Valid controls allowed: {total['controls_allowed']} of {total['controls']}.",
        f"- Adapter errors: {total['errors']}.",
        "",
        "| Case | Cat. | Role | Check | Expected | Observed | Evidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        mark = "" if r.correct else " (wrong)"
        evidence = r.evidence.replace("|", "/").replace("\n", " ")
        lines.append(
            f"| `{r.id}` | {r.category} | {r.role} | `{r.check}` | {r.expected} | "
            f"{r.observed}{mark} | {evidence} |"
        )
    lines += ["", "## Unresolved defects", ""]
    wrong = [r for r in results if not r.correct]
    lines += [f"- `{r.id}`: expected {r.expected}, observed {r.observed}." for r in wrong]
    lines += [f"- Category {g.category}: {g.gap}" for g in suite.untested]
    lines += ["", "## Limits", "", *LIMITS]
    return "\n".join(lines) + "\n"
